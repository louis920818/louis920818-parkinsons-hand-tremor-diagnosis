def carr(name,vals,typ,per=20):
    s=f"static const {typ} {name}[{len(vals)}] = {{\n"
    for i in range(0,len(vals),per):
        ch=vals[i:i+per]
        s+="  "+(",".join(f"{v:.7g}f" for v in ch) if typ=="float" else ",".join(str(int(v)) for v in ch))+",\n"
    return s+"};\n"
