def flatten(bst):
    FE=[];TH=[];LE=[];RI=[];RO=[]
    for ds in bst.get_dump(dump_format="json"):
        tree=json.loads(ds); order=[]
        def walk(n):
            order.append(n)
            if "children" in n: walk(n["children"][0]); walk(n["children"][1])
        walk(tree); idx={}; base=len(FE)
        for k,n in enumerate(order): idx[n["nodeid"]]=base+k
        RO.append(idx[tree["nodeid"]])
        for n in order:
            if "leaf" in n: FE.append(-1);TH.append(float(n["leaf"]));LE.append(-1);RI.append(-1)
            else:
                FE.append(int(n["split"][1:])); TH.append(float(n["split_condition"]))
                LE.append(idx[n["yes"]]); RI.append(idx[n["no"]])
    return FE,TH,LE,RI,RO
def pym(F,T,L,R,RO,x):
    s=0.0
    for r in RO:
        i=r
        while F[i]!=-1: i=L[i] if x[F[i]]<T[i] else R[i]
        s+=T[i]
    return s
def train_export(pos,neg,tag):
    m=np.isin(y,[pos,neg]); Xm,ym=X[m],(y[m]==pos).astype(int)
    med=np.nanmedian(Xm,0); Xi=np.where(np.isnan(Xm),med,Xm)
    bst=xgb.train(P,xgb.DMatrix(Xi,label=ym),NROUND)
    Fl=flatten(bst); dm=xgb.DMatrix(Xi); bm=bst.predict(dm,output_margin=True)
    mys=np.array([pym(*Fl,Xi[k]) for k in range(len(Xi))])
    inter=float(np.median(bm-mys))
    prob_b=bst.predict(dm); prob_my=1/(1+np.exp(-(mys+inter)))
    perr=float(np.max(np.abs(prob_b-prob_my)))
    print(f"[{tag}] trees={len(Fl[4])} nodes={len(Fl[0])} prob_err={perr:.2e}")
    return dict(F=Fl[0],T=Fl[1],L=Fl[2],R=Fl[3],RO=Fl[4],inter=inter,med=med.tolist())
